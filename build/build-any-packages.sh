#!/bin/bash
# Build the omarchy packages the image needs that pkgs.omarchy.org only ships
# for x86_64. Runs INSIDE an archlinux/archlinux container (any arch):
#
#   docker run --rm -v "$repo:/work" archlinux/archlinux:latest \
#     bash /work/build/build-any-packages.sh
#
# Everything built here is arch=('any') — bash/config/font/QML content — so an
# x86 container can package for aarch64 at native speed. Compiled aarch64
# packages are NOT built here (see pkgs/README.md for that pipeline).
#
# Builds:
#   1. omarchy-keyring, omarchy-settings, omarchy, omarchy-nvim  (the runtime)
#   2. base-list arch=('any') packages ALARM doesn't carry
#      (fonts, ufw-docker, yaru-icon-theme, …) + tzupdate (pure python,
#      declared x86_64 upstream only by omission)
#   3. omarchy-cm5-shims: an empty provider for runtime dependencies that
#      don't exist on aarch64 and don't apply to Pi-firmware boot (limine and
#      friends), so pacman's dependency graph stays honest without them.
#
# Inputs:  /work/build/resolved/alarm-names.txt   (from resolve-packages.sh)
#          /work/upstream.lock                     (pins basecamp/omarchy ref)
# Output:  /work/build/pkgs-out/*.pkg.tar.zst (+ BUILT.txt, SHIMMED.txt)
set -euo pipefail

WORK=${WORK:-/work}
OUT=$WORK/build/pkgs-out
ALARM_NAMES=$WORK/build/resolved/alarm-names.txt
mkdir -p "$OUT"

# shellcheck source=../upstream.lock
source "$WORK/upstream.lock"

# imagemagick: omarchy-settings icon generation; neovim/nodejs/npm/
# tree-sitter-cli: omarchy-nvim vendors LazyVim plugins at build time.
pacman -Syu --noconfirm --needed base-devel git imagemagick sudo \
  neovim nodejs npm tree-sitter-cli >/dev/null
useradd -m builder 2>/dev/null || true
echo 'builder ALL=(ALL) NOPASSWD: ALL' >/etc/sudoers.d/builder

build_dir=/home/builder/build
sudo -u builder mkdir -p "$build_dir"

git clone --depth 1 https://github.com/omacom-io/omarchy-pkgs "$build_dir/omarchy-pkgs"
chown -R builder "$build_dir"
echo "omarchy-pkgs @ $(git -C "$build_dir/omarchy-pkgs" rev-parse --short HEAD)" >"$OUT/BUILT.txt"

alarm_has() { grep -qxF "$1" "$ALARM_NAMES"; }

# makepkg -d: skip dep checks — 'any' package() steps only copy files, and the
# container doesn't need hyprland/plymouth/etc. installed to tar them up.
build_one() {
  local name=$1 dir=$build_dir/omarchy-pkgs/pkgbuilds/$1
  shift
  [[ -d $dir ]] || { echo "PKGBUILD missing: $name" >&2; return 1; }
  for mutate in "$@"; do sudo -u builder bash -c "cd '$dir' && $mutate"; done
  (cd "$dir" && sudo -u builder env OMARCHY_REF="$OMARCHY_REF" \
    makepkg -d -f --skipchecksums --skippgpcheck --noconfirm) || return 1
  cp "$dir"/*.pkg.tar.zst "$OUT/"
  echo "$name" >>"$OUT/BUILT.txt"
}

# 1. The runtime. omarchy + omarchy-settings must be built from the SAME
# commit; pin both to upstream.lock's ref so the image matches the audit.
pin_ref="sed -i \"s/^_commit=.*/_commit='$OMARCHY_REF'/\" PKGBUILD"
build_one omarchy-keyring
build_one omarchy-settings "$pin_ref"
build_one omarchy "$pin_ref"
build_one omarchy-nvim

# 2. arch=('any') base-list packages ALARM doesn't carry.
for pkg in ttf-ia-writer ttf-jetbrains-mono-nerd-basic ufw-docker yaru-icon-theme tobi-try xdg-terminal-exec; do
  if alarm_has "$pkg"; then
    echo "skip $pkg (ALARM has it)" >&2
  else
    build_one "$pkg" || echo "FAILED: $pkg" >>"$OUT/BUILT.txt"
  fi
done
# tzupdate is pure python; upstream PKGBUILD just never claimed 'any'.
if ! alarm_has tzupdate; then
  build_one tzupdate "sed -i \"s/^arch=.*/arch=('any')/\" PKGBUILD" || echo "FAILED: tzupdate" >>"$OUT/BUILT.txt"
fi

# 3. Shims: hard deps of the built packages that exist neither on ALARM nor
# among what we built. On a Pi the limine bootloader stack is structurally
# unused (firmware boots the kernel); anything else that lands here is a real
# gap and is reported loudly.
mapfile -t deps < <(
  for f in "$OUT"/*.pkg.tar.zst; do
    bsdtar -xOf "$f" .PKGINFO | awk -F' = ' '$1=="depend"{sub(/[<>=].*/,"",$2); print $2}'
  done | sort -u
)
mapfile -t built_names < <(
  for f in "$OUT"/*.pkg.tar.zst; do
    bsdtar -xOf "$f" .PKGINFO | awk -F' = ' '$1=="pkgname"{print $2}'
  done | sort -u
)
missing=()
for d in "${deps[@]}"; do
  alarm_has "$d" && continue
  printf '%s\n' "${built_names[@]}" | grep -qxF "$d" && continue
  missing+=("$d")
done

: >"$OUT/SHIMMED.txt"
if ((${#missing[@]})); then
  printf '%s\n' "${missing[@]}" >"$OUT/SHIMMED.txt"
  echo "shimming unavailable deps: ${missing[*]}" >&2
  shim_dir=$build_dir/omarchy-cm5-shims
  sudo -u builder mkdir -p "$shim_dir"
  provides=$(printf "'%s' " "${missing[@]}")
  sudo -u builder tee "$shim_dir/PKGBUILD" >/dev/null <<EOF
# Auto-generated by build-any-packages.sh — provider shim for omarchy runtime
# dependencies that have no aarch64 package. Each name listed here is a
# feature gap or a structural no-op on Pi-firmware boot; see SHIMMED.txt in
# the build report.
pkgname=omarchy-cm5-shims
pkgver=1
pkgrel=1
pkgdesc='Provider shim for omarchy deps absent on aarch64 (Pi firmware boots the kernel directly)'
arch=('any')
provides=($provides)
package() { :; }
EOF
  (cd "$shim_dir" && sudo -u builder makepkg -d -f --noconfirm)
  cp "$shim_dir"/*.pkg.tar.zst "$OUT/"
  echo "omarchy-cm5-shims" >>"$OUT/BUILT.txt"
fi

echo "=== built packages ==="
ls -la "$OUT"
